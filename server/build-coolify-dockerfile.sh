#!/bin/sh
# Builds Dockerfile.coolify: one self-contained Dockerfile (code inlined via heredocs)
# that can be pasted into Coolify's "Dockerfile" resource — no Git repo needed.
set -e
cd "$(dirname "$0")"
{
  echo '# syntax=docker/dockerfile:1'
  echo '# Generated by build-coolify-dockerfile.sh — do not edit by hand.'
  echo 'FROM python:3.12-slim'
  echo 'RUN apt-get update && apt-get install -y --no-install-recommends ffmpeg ca-certificates && rm -rf /var/lib/apt/lists/*'
  echo 'COPY --from=denoland/deno:bin /deno /usr/local/bin/deno'
  echo 'WORKDIR /srv'
  echo "COPY <<'EOF_REQ' requirements.txt"
  cat requirements.txt
  echo 'EOF_REQ'
  echo 'RUN pip install --no-cache-dir -r requirements.txt'
  echo "COPY <<'EOF_MAIN' app/main.py"
  cat app/main.py
  echo 'EOF_MAIN'
  echo "COPY <<'EOF_ENTRY' entrypoint.sh"
  cat entrypoint.sh
  echo 'EOF_ENTRY'
  echo 'RUN chmod +x entrypoint.sh && touch app/__init__.py && useradd -m -u 1000 app && mkdir -p /data/cache && chown -R app:app /data /srv /usr/local/lib/python3.12/site-packages /usr/local/bin'
  echo 'USER app'
  echo 'EXPOSE 8000'
  echo 'HEALTHCHECK --interval=30s --timeout=5s CMD python -c "import urllib.request;urllib.request.urlopen(\"http://127.0.0.1:8000/health\")"'
  echo 'ENTRYPOINT ["./entrypoint.sh"]'
} > Dockerfile.coolify
echo "wrote Dockerfile.coolify ($(wc -l < Dockerfile.coolify) lines)"
